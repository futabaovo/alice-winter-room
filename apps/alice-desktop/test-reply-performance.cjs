const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {normalizeEvents,validateSpeechCues,splitSentences}=require('./reply-plan.cjs');
const {replySchema}=require('./chat-host.cjs');
(async()=>{
  const {ReplyPerformance}=await import('data:text/javascript;base64,'+fs.readFileSync(path.join(__dirname,'web/reply-performance.js')).toString('base64'));
  const ids=require('./character/expressions.json').map(e=>e.id),ja='そう。少し、面白いわ。';
  const event={sentenceIndex:1,emotion:'thinking',strength:.35,hold:1};
  assert.deepEqual(splitSentences(ja),['そう。','少し、面白いわ。']);
  assert.deepEqual(normalizeEvents(undefined,ja),[]);
  assert.deepEqual(normalizeEvents([{...event,sentenceIndex:7},{...event,emotion:'neutral'},event,{...event,strength:2}],ja),[event]);
  assert.equal(normalizeEvents([{...event,strength:20,hold:100}],ja)[0].strength,.6);
  const cues=[{start:0,end:.8,ja:'そう。'},{start:1.02,end:4,ja:'少し、面白いわ。'}];
  assert.equal(validateSpeechCues(cues,ja,4).length,2);
  assert.deepEqual(validateSpeechCues([{...cues[0]}, {...cues[1],ja:'違う。'}],ja,4),[]);
  assert.deepEqual(validateSpeechCues([{...cues[0]}, {...cues[1],start:.5}],ja,4),[]);
  assert(replySchema.required.includes('expressionEvents'));
  assert.equal(replySchema.properties.expressionEvents.items.additionalProperties,false);
  let now=0,mood=0,speech={id:null},p;
  p=new ReplyPerformance({getSpeech:()=>speech,getMood:()=>mood,displayMood:i=>{mood=i;},moodIds:ids,now:()=>now});
  const bind=events=>{const t=p.reserve();p.accept(t,{ja,expressionEvents:events});speech={id:'test',time:0,playing:true};p.attachSpeech(t,{id:'test',speechCues:cues});return t;};
  bind([]);speech.time=2;assert.equal(p.update(),null);assert.equal(mood,0);
  bind([event]);speech.time=.7;assert.equal(p.update(),null);
  speech.time=1.42;assert.equal(p.update().index,5);const weight=p.update().weight;
  speech.playing=false;speech.paused=true;now=20;assert.equal(p.update().weight,weight);
  speech.time=.3;assert.equal(p.update(),null);assert.equal(mood,0);
  speech.time=1.42;assert.equal(p.update().index,5);
  p.manualOverride();mood=2;speech.time=1.6;assert.equal(p.update(),null);assert.equal(mood,2);
  const pending=p.reserve();p.manualOverride();assert.equal(p.accept(pending,{ja,expressionEvents:[event]}),false);
  mood=0;bind([event]);speech.time=1.42;p.update();speech.id=null;assert.equal(p.update(),null);assert.equal(mood,0);
  bind([event]);speech.time=1.42;p.update();speech.ended=true;p.update();now+=.6;assert.equal(p.update(),null);assert.equal(mood,0);
  speech.ended=false;speech.time=1.42;speech.playing=true;assert.equal(p.update().index,5);
  p.setEnabled(false);assert.equal(p.update(),null);const off=p.reserve();assert.equal(p.accept(off,{ja,expressionEvents:[event]}),false);
  p.setEnabled(true);mood=0;const text=p.reserve();p.accept(text,{ja,expressionEvents:[event]});p.startText(text);now+=2.2;assert.equal(p.update().index,5);
  now+=20;p.update();now+=1;assert.equal(p.update(),null);assert.equal(mood,0);
  bind([{...event,sentenceIndex:0,hold:1.8},{...event,emotion:'rest',hold:.6}]);assert(p.diagnostic().timeline[0].end<=1.02);
  speech.time=3;assert.equal(p.update(),null); // Old expression cannot resurface after the next one.
  console.log(JSON.stringify({ok:true,checks:['safe empty plan','bounded events','strict schema','validated real sentence cues','wait before target sentence','audio clock','pause','seek both ways','manual override including pending reply','speech replacement','end release','replay','disable','text-only fallback','no resurfacing overlap']}));
})().catch(e=>{console.error(e);process.exitCode=1;});
